/**
 * SoftBadge: A subtle, calm, botanical chip that replaces loud unicode emojis.
 */
export function SoftBadge({
  icon,
  label,
  children,
  variant = "emerald",
  className = "",
}: {
  icon?: SoftIconName;
  label?: string;
  children?: React.ReactNode;
  variant?: "emerald" | "slate" | "indigo" | "amber" | "rose";
  className?: string;
}) {
  const styles: Record<string, { bg: string; text: string; iconColor: string; border: string }> = {
    emerald: {
      bg: "rgba(16, 185, 129, 0.08)",
      text: "#065f46",
      iconColor: "#059669",
      border: "rgba(16, 185, 129, 0.2)",
    },
    slate: {
      bg: "rgba(100, 116, 139, 0.08)",
      text: "#334155",
      iconColor: "#64748b",
      border: "rgba(100, 116, 139, 0.18)",
    },
    indigo: {
      bg: "rgba(99, 102, 241, 0.08)",
      text: "#3730a3",
      iconColor: "#4f46e5",
      border: "rgba(99, 102, 241, 0.2)",
    },
    amber: {
      bg: "rgba(245, 158, 11, 0.08)",
      text: "#92400e",
      iconColor: "#d97706",
      border: "rgba(245, 158, 11, 0.22)",
    },
    rose: {
      bg: "rgba(244, 63, 94, 0.08)",
      text: "#9f1239",
      iconColor: "#e11d48",
      border: "rgba(244, 63, 94, 0.2)",
    },
  };

  const v = styles[variant] || styles.emerald;

  return (
    <span
      className={`si-1 px-2.5 tracking-wide ${className}`}
      style={{
        backgroundColor: v.bg,
        color: v.text,
        border: `1px solid ${v.border}`,
      }}
    >
      {icon && <SoftIcon name={icon} size={13} color={v.iconColor} strokeWidth={2} />}
      <span>{label || children}</span>
    </span>
  );
}
