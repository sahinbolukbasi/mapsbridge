function normalizeKey(input: string): string {
  return (input || "")
    .toLowerCase()
    .replace(/ı/g, "i")
    .replace(/ğ/g, "g")
    .replace(/ü/g, "u")
    .replace(/ş/g, "s")
    .replace(/ö/g, "o")
    .replace(/ç/g, "c")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function findCityIntelligence(destinationOrPrompt: string): CityIntelligenceProfile | null {
  const norm = normalizeKey(destinationOrPrompt);
  if (!norm) return null;

  for (const city of CURATED_CITY_CATALOG) {
    if (norm.includes(normalizeKey(city.canonicalName)) || norm.includes(city.cityKey)) {
      return city;
    }
    for (const alias of city.aliases) {
      const normAlias = normalizeKey(alias);
      if (normAlias && (norm === normAlias || norm.includes(normAlias))) {
        return city;
      }
    }
  }
  return null;
}

export function selectCuratedPlacesForTrip(
  destinationOrPrompt: string,
  options?: {
    days?: number;
    interests?: string[];
    maxPlaces?: number;
  },
): CuratedPlaceIntel[] {
  const city = findCityIntelligence(destinationOrPrompt);
  if (!city) return [];

  const days = Math.max(1, Math.min(options?.days ?? 3, 7));
  const maxPlaces = options?.maxPlaces ?? Math.max(8, days * 4);
  const interestTokens = (options?.interests ?? []).map((i) => normalizeKey(i)).filter(Boolean);

  const scored = city.places.map((p) => {
    let bonus = 0;
    if (interestTokens.length > 0) {
      for (const token of interestTokens) {
        if (
          p.tags.some((t) => normalizeKey(t).includes(token) || token.includes(normalizeKey(t))) ||
          normalizeKey(p.category).includes(token)
        ) {
          bonus += 0.08;
        }
      }
    }
    return { place: p, score: p.uniquenessScore + bonus };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, maxPlaces).map((s) => s.place);
}

